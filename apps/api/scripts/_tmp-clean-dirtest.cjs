const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();
const TAG = process.argv[2] || 'DIRTEST';
(async () => {
  const emailTag = TAG.toLowerCase();
  const clientUsers = await prisma.user.findMany({ where: { email: { contains: emailTag } }, select: { id: true } });
  await prisma.passwordResetToken.deleteMany({ where: { userId: { in: clientUsers.map((u) => u.id) } } }).catch(() => {});
  await prisma.refreshToken.deleteMany({ where: { userId: { in: clientUsers.map((u) => u.id) } } }).catch(() => {});
  await prisma.userRole.deleteMany({ where: { userId: { in: clientUsers.map((u) => u.id) } } }).catch(() => {});
  await prisma.user.deleteMany({ where: { id: { in: clientUsers.map((u) => u.id) } } });
  await prisma.contact.deleteMany({ where: { email: { contains: emailTag } } });
  await prisma.reservationRequest.deleteMany({ where: { email: { contains: emailTag } } });
  const prospects = await prisma.prospect.findMany({ where: { nom: { contains: TAG } }, select: { id: true } });
  const dossiers = await prisma.dossierVente.findMany({ where: { OR: [{ prospectId: { in: prospects.map((p) => p.id) } }, { terrain: { referenceInterne: { contains: TAG } } }] }, select: { id: true } });
  const ids = dossiers.map((d) => d.id);
  await prisma.commissionVente.deleteMany({ where: { dossierVenteId: { in: ids } } }).catch(() => {});
  await prisma.documentVente.deleteMany({ where: { dossierVenteId: { in: ids } } });
  await prisma.paiement.deleteMany({ where: { dossierVenteId: { in: ids } } });
  await prisma.echeancePaiement.deleteMany({ where: { dossierVenteId: { in: ids } } });
  await prisma.reservation.deleteMany({ where: { dossierVenteId: { in: ids } } });
  await prisma.dossierVente.deleteMany({ where: { id: { in: ids } } });
  await prisma.objectifCommercial.deleteMany({ where: { notes: { contains: TAG } } }).catch(() => {});
  await prisma.prospect.deleteMany({ where: { id: { in: prospects.map((p) => p.id) } } });
  const mandats = await prisma.mandat.findMany({ where: { referenceInterne: { contains: TAG } }, select: { id: true } });
  await prisma.mandatLot.deleteMany({ where: { mandatId: { in: mandats.map((m) => m.id) } } });
  await prisma.mandatDocument.deleteMany({ where: { mandatId: { in: mandats.map((m) => m.id) } } });
  await prisma.mandat.deleteMany({ where: { id: { in: mandats.map((m) => m.id) } } });
  await prisma.terrain.deleteMany({ where: { referenceInterne: { contains: TAG } } });
  await prisma.proprietaire.deleteMany({ where: { lastName: { contains: TAG } } });
  console.log('nettoyé :', { dossiers: ids.length, prospects: prospects.length, mandats: mandats.length, comptesClient: clientUsers.length });
  await prisma.$disconnect();
})().catch((e) => { console.error(e.message); process.exit(1); });
